_ALL_FACTOR_IDS = list(_TEMPLATES)
# Trims the single-factor set from 32 to 28 (keeping the dataset in the
# 60-100 range overall) by skipping the very_low variant for a few factors
# that are still exercised at very_low elsewhere (multi-factor combos,
# missing-information, paraphrase clusters).
_SINGLE_FACTOR_SKIP_LEVELS = {
    ("creative_expression", "very_low"),
    ("values_alignment", "very_low"),
    ("option_value", "very_low"),
    ("long_term_value", "very_low"),
}


def _single_factor_scenarios() -> list[dict[str, Any]]:
    scenarios = []
    for factor_id, levels in _TEMPLATES.items():
        for level, fragment in levels.items():
            if (factor_id, level) in _SINGLE_FACTOR_SKIP_LEVELS:
                continue
            text = f"I'm weighing a decision. Here's the thing: {fragment}."
            scenarios.append(
                {
                    "id": f"single_{factor_id}_{level}",
                    "category": "single_factor_clear",
                    "scenario": text,
                    "gold_factors": {factor_id: level},
                    "notes": "Single-factor, unambiguous; sentence built from the gold label.",
                }
            )
    return scenarios


def _multi_factor_scenarios() -> list[dict[str, Any]]:
    combos = [
        (("skill_growth", "very_high"), ("financial_return", "very_low")),
        (("financial_return", "very_high"), ("time_demand", "very_high")),
        (("autonomy", "very_high"), ("stability", "very_low")),
        (("location_fit", "very_high"), ("skill_growth", "very_low")),
        (("downside_risk", "very_high"), ("reversibility", "very_high")),
        (("values_alignment", "very_high"), ("financial_return", "very_low")),
        (("social_fit", "very_low"), ("intrinsic_interest", "very_high")),
        (("health_wellbeing", "very_low"), ("financial_security", "very_high")),
        (("creative_expression", "very_high"), ("stability", "very_low")),
        (("option_value", "very_high"), ("long_term_value", "very_high")),
        (
            ("skill_growth", "very_high"),
            ("financial_return", "very_high"),
            ("time_demand", "very_high"),
        ),
        (
            ("autonomy", "very_high"),
            ("social_fit", "very_high"),
            ("financial_security", "very_low"),
        ),
        (
            ("downside_risk", "very_low"),
            ("reversibility", "very_low"),
            ("stability", "very_high"),
        ),
    ]
    scenarios = []
    for index, combo in enumerate(combos):
        fragments = [_TEMPLATES[fid][level] for fid, level in combo]
        text = "Considering an option where " + "; also, ".join(fragments) + "."
        gold = dict(combo)
        scenarios.append(
            {
                "id": f"multi_{index:02d}",
                "category": "multi_factor",
                "scenario": text,
                "gold_factors": gold,
                "notes": f"{len(combo)}-factor combination, each clause maps to one factor.",
            }
        )
    return scenarios


