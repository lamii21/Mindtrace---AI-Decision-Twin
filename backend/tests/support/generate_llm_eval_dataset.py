"""Generates `tests/support/data/llm_eval_dataset.json` (M5 §14).

Not imported by any test - a one-off authoring tool, run manually and its
output committed. Every scenario's gold label is constructed *from* the
sentence template, not guessed after the fact, so correctness is by
construction, not by an LLM's own say-so (M5 §14: "gold labels must not be
generated by the same LLM being evaluated" - here they are not generated by
any LLM at all).
"""

