def _paraphrase_clusters() -> list[dict[str, Any]]:
    clusters = [
        (
            "skill_growth",
            "very_high",
            [
                "It would teach me an enormous amount of new technical skill.",
                "I'd walk away having learned a massive amount technically.",
                "The learning curve here is steep - in a very good way, skill-wise.",
            ],
        ),
        (
            "financial_return",
            "very_low",
            [
                "The pay is essentially nothing.",
                "Financially, this role pays almost nothing at all.",
                "There's barely any money in it.",
            ],
        ),
        (
            "downside_risk",
            "very_high",
            [
                "If this goes wrong, the fallout would be severe.",
                "The worst-case outcome here is genuinely severe.",
                "Things could go badly wrong, and recovery would be hard.",
            ],
        ),
        (
            "autonomy",
            "very_high",
            [
                "I would have complete control over how I work.",
                "Nobody would be telling me how to do my work - full control.",
                "Total autonomy over my own working style, essentially.",
            ],
        ),
        (
            "reversibility",
            "very_low",
            [
                "There is no going back once this decision is made.",
                "Once decided, this cannot be undone.",
                "This is a one-way door - no reversing course later.",
            ],
        ),
    ]
    scenarios = []
    for cluster_index, (factor_id, level, variants) in enumerate(clusters):
        for variant_index, text in enumerate(variants):
            scenarios.append(
                {
                    "id": f"paraphrase_{cluster_index:02d}_{variant_index}",
                    "category": "paraphrase",
                    "scenario": text,
                    "gold_factors": {factor_id: level},
                    "notes": f"paraphrase cluster {cluster_index}, variant {variant_index}",
                    "paraphrase_cluster": cluster_index,
                }
            )
    return scenarios


