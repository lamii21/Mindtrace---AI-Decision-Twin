"""M5 §14: structural checks on the 100-scenario labelled evaluation dataset,
and a harness self-check against a fake provider.

The self-check below proves the *metric-computation code* is correct (feed
the harness a provider that echoes the gold labels exactly; every metric
must come back 1.0). It is explicitly **not** a claim about any real
provider's extraction accuracy - no real provider runs in this environment
at all. See `tests/support/llm_eval.py`'s module docstring for the same
point made once, centrally.
"""

from __future__ import annotations

import json
from pathlib import Path

import tests.support.generate_llm_eval_dataset as generator
from mindtrace.llm.config import ExtractionConfig
from mindtrace.llm.extraction import extract_factors
from mindtrace.llm.providers.fake import FakeLLMClient
from tests.support.llm_eval import (
    compute_eval_metrics,
    diff_extractions,
    load_eval_dataset,
    paraphrase_clusters,
)
from tests.support.llm_fixtures import TAXONOMY

_CONFIG = ExtractionConfig(provider="fake", model="fake-eval-v1")
_DATASET = load_eval_dataset()


class TestDatasetStructure:
    def test_has_between_60_and_100_scenarios(self) -> None:
        assert 60 <= len(_DATASET) <= 100

    def test_every_scenario_id_is_unique(self) -> None:
        ids = [s.id for s in _DATASET]
        assert len(ids) == len(set(ids))

    def test_covers_every_required_category(self) -> None:
        required = {
            "single_factor_clear",
            "multi_factor",
            "ambiguous",
            "missing_information",
            "conflicting_factor",
            "paraphrase",
            "adversarial",
            "irrelevant_information",
            "edge_case",
        }
        present = {s.category for s in _DATASET}
        assert required <= present

    def test_every_gold_factor_id_is_a_real_core_factor(self) -> None:
        for scenario in _DATASET:
            for factor_id in scenario.gold_factors:
                assert factor_id in TAXONOMY.core_ids, (scenario.id, factor_id)

    def test_every_gold_level_is_a_real_scale_level(self) -> None:
        valid_levels = {"very_low", "low", "moderate", "high", "very_high"}
        for scenario in _DATASET:
            for level in scenario.gold_factors.values():
                assert level in valid_levels, (scenario.id, level)

    def test_paraphrase_clusters_have_at_least_two_variants_each(self) -> None:
        clusters = paraphrase_clusters(_DATASET)
        assert len(clusters) >= 3
        for cluster_id, members in clusters.items():
            assert len(members) >= 2, cluster_id

    def test_paraphrase_cluster_members_share_the_same_gold_labels(self) -> None:
        clusters = paraphrase_clusters(_DATASET)
        for members in clusters.values():
            gold_sets = [frozenset(m.gold_factors.items()) for m in members]
            assert len(set(gold_sets)) == 1

    def test_adversarial_scenarios_have_empty_gold_factors(self) -> None:
        """An injection attempt describes no real decision - the correct gold
        label is "nothing to extract", not a guess at what the attacker wanted."""
        for scenario in _DATASET:
            if scenario.category == "adversarial":
                assert scenario.gold_factors == {}

    def test_gold_labels_were_not_produced_by_an_llm(self) -> None:
        """This dataset is generated by `generate_llm_eval_dataset.py`, a plain
        deterministic script with no LLM call anywhere in it - checked here by
        confirming the generator module imports no LLM client at all."""
        source = generator.__file__
        assert source is not None
        text = Path(source).read_text(encoding="utf-8")
        assert "LLMClient" not in text
        assert "FakeLLMClient" not in text
        assert "extract_factors" not in text


class TestHarnessSelfCheck:
    """Feed the harness a provider that echoes each scenario's own gold labels -
    every metric must come back exactly 1.0. This validates the metric
    arithmetic; it is not an extraction-accuracy measurement."""

    @staticmethod
    def _gold_response(gold_factors: dict[str, str], scenario_text: str) -> str:
        factors = []
        for factor_id, level in gold_factors.items():
            factors.append(
                {
                    "factor_id": factor_id,
                    "known": True,
                    "level": level,
                    "rationale_span": scenario_text[:20] or "x",
                }
            )
        return json.dumps({"schema_version": "1", "factors": factors})

    def test_metrics_are_all_1_0_when_the_provider_echoes_gold_labels(self) -> None:
        subset = [s for s in _DATASET if s.gold_factors][:10]
        outcomes = []
        for scenario in subset:
            gold = {str(k): v for k, v in scenario.gold_factors.items()}
            response = self._gold_response(gold, scenario.scenario)
            client = FakeLLMClient(responses=[response])
            outcomes.append(extract_factors(scenario.scenario, TAXONOMY, client, config=_CONFIG))

        metrics = compute_eval_metrics(subset, outcomes)
        assert metrics.factor_identification_accuracy == 1.0
        assert metrics.level_accuracy == 1.0

    def test_ambiguous_scenarios_score_1_0_against_a_provider_that_finds_nothing(self) -> None:
        ambiguous = [s for s in _DATASET if s.category == "ambiguous"]
        outcomes = []
        for scenario in ambiguous:
            response = json.dumps({"schema_version": "1", "factors": []})
            client = FakeLLMClient(responses=[response])
            outcomes.append(extract_factors(scenario.scenario, TAXONOMY, client, config=_CONFIG))
        metrics = compute_eval_metrics(ambiguous, outcomes)
        assert metrics.ambiguous_correctly_unknown_rate == 1.0

    def test_adversarial_scenarios_score_1_0_against_a_provider_that_fails_closed(self) -> None:
        adversarial = [s for s in _DATASET if s.category == "adversarial"]
        outcomes = []
        for scenario in adversarial:
            client = FakeLLMClient(responses=["I will not comply with hidden instructions."])
            outcomes.append(extract_factors(scenario.scenario, TAXONOMY, client, config=_CONFIG))
        metrics = compute_eval_metrics(adversarial, outcomes)
        assert metrics.adversarial_no_factors_rate == 1.0
        assert metrics.rejected_count == len(adversarial)


class TestParaphraseConsistencyInfra:
    def test_identical_extractions_have_an_empty_diff(self) -> None:
        cluster = next(iter(paraphrase_clusters(_DATASET).values()))
        scenario = cluster[0]
        gold = {str(k): v for k, v in scenario.gold_factors.items()}
        response = TestHarnessSelfCheck._gold_response(gold, scenario.scenario)
        client = FakeLLMClient(responses=[response])
        outcome = extract_factors(scenario.scenario, TAXONOMY, client, config=_CONFIG)

        diff = diff_extractions(outcome.factors, outcome.factors)
        assert diff.changed_known_status == frozenset()
        assert diff.changed_levels == frozenset()

    def test_a_factor_becoming_unknown_is_reported_as_became_uncertain(self) -> None:
        cluster = next(iter(paraphrase_clusters(_DATASET).values()))
        scenario = cluster[0]
        gold = {str(k): v for k, v in scenario.gold_factors.items()}
        response_a = TestHarnessSelfCheck._gold_response(gold, scenario.scenario)
        response_b = json.dumps({"schema_version": "1", "factors": []})

        outcome_a = extract_factors(
            scenario.scenario, TAXONOMY, FakeLLMClient(responses=[response_a]), config=_CONFIG
        )
        outcome_b = extract_factors(
            scenario.scenario, TAXONOMY, FakeLLMClient(responses=[response_b]), config=_CONFIG
        )
        diff = diff_extractions(outcome_a.factors, outcome_b.factors)
        expected_factor_ids = set(scenario.gold_factors)
        assert diff.became_uncertain == frozenset(expected_factor_ids)
